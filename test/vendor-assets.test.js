const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');

const root = path.join(__dirname, '..', '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
// The static allowlist the desktop shell and the dev server share (both serve
// /vendor/* from assets/vendor).
const serverSource = fs.readFileSync(
  path.join(root, 'src-tauri/src/protocol/static_assets.rs'),
  'utf8',
);

test('browser vendor packages are build-only dependencies', () => {
  for (const dependency of ['@xterm/addon-fit', '@xterm/xterm', 'dompurify']) {
    assert.equal(
      manifest.dependencies?.[dependency],
      undefined,
      `${dependency} must not enter the production install`,
    );
    assert.equal(
      typeof manifest.devDependencies?.[dependency],
      'string',
      `${dependency} is still required to build the client`,
    );
  }
});

test('the client build emits only the browser vendor files the server exposes', () => {
  for (const file of ['xterm.js', 'xterm.css', 'xterm-fit.js']) {
    const built = path.join(root, 'assets', 'vendor', file);
    assert.ok(fs.statSync(built).size > 0, `${file} must be generated by build:client`);
    assert.match(serverSource, new RegExp(`assets/vendor/${file.replace('.', '\\.')}`));
  }
  assert.doesNotMatch(serverSource, /['"]node_modules\/(?:@xterm|lucide)/);
});

test('the launcher defers terminal assets and uses the shared UX catalog', () => {
  const index = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
  const agentFeature = fs
    .readdirSync(path.join(root, 'src/client/features/agents'))
    .filter((file) => file.endsWith('.js'))
    .map((file) => fs.readFileSync(path.join(root, 'src/client/features/agents', file), 'utf8'))
    .join('\n');
  assert.doesNotMatch(index, /vendor\/xterm(?:-fit)?\.js|vendor\/xterm\.css/);
  assert.match(agentFeature, /ensureTerminalAssets\(\)/);
  assert.ok(
    fs.statSync(path.join(root, 'assets', 'app.bundle.js')).size < 270_000,
    'minified launcher bundle, including lazy app entry points, should stay below 270 KB',
  );
});

test('the teleprompter editor loads separately from the launcher startup bundle', () => {
  const launcher = fs.readFileSync(path.join(root, 'assets/app.bundle.js'), 'utf8');
  const editor = fs.readFileSync(path.join(root, 'assets/teleprompter.bundle.js'), 'utf8');
  assert.ok(!launcher.includes('Your words, just below the camera.'));
  assert.ok(editor.includes('Your words, just below the camera.'));
  assert.ok(editor.length < 45_000, 'the lazy editor stays compact');
});

test('the UX catalog and approved WhatsApp brand cover every client icon', () => {
  const clientFiles = (directory) =>
    fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
      const target = path.join(directory, entry.name);
      return entry.isDirectory() ? clientFiles(target) : /\.jsx?$/.test(entry.name) ? [target] : [];
    });
  const sources = [
    fs.readFileSync(path.join(root, 'index.html'), 'utf8'),
    fs.readFileSync(path.join(root, 'app.js'), 'utf8'),
    ...clientFiles(path.join(root, 'src/client')).map((file) => fs.readFileSync(file, 'utf8')),
  ];
  const names = new Set();
  for (const source of sources) {
    for (const match of source.matchAll(/data-ux-icon=["']([a-z0-9-]+)["']/g)) names.add(match[1]);
    for (const match of source.matchAll(/\bicon\(["']([a-z0-9-]+)["']\)/g)) names.add(match[1]);
  }

  const dom = new JSDOM([...names].map((name) => `<i data-ux-icon="${name}"></i>`).join(''), {
    runScripts: 'dangerously',
  });
  dom.window.MessageChannel = class {
    constructor() {
      this.port1 = {};
      this.port2 = { postMessage() {} };
    }
  };
  const script = dom.window.document.createElement('script');
  script.textContent = fs.readFileSync(path.join(root, 'assets/ux.bundle.js'), 'utf8');
  dom.window.document.head.append(script);
  dom.window.HabibiUx.createIcons();
  assert.equal(dom.window.document.querySelectorAll('svg').length, names.size);
  assert.equal(dom.window.document.querySelector('i[data-ux-icon]'), null);
  const download = dom.window.document.querySelector('svg[data-ux-icon="download"]');
  const reference = fs.readFileSync(
    path.join(root, 'node_modules/@clidey/ux/icons/svg/download.svg'),
    'utf8',
  );
  const pathData = new JSDOM(reference).window.document.querySelector('path').getAttribute('d');
  assert.ok(
    decodeURIComponent(download.getAttribute('style')).includes(pathData),
    'the rendered mask must contain the library SVG artwork',
  );
  const whatsapp = dom.window.document.querySelector('svg[data-ux-icon="whatsapp"]');
  assert.equal(whatsapp.dataset.iconSource, 'whatsapp-brand');
  const brand = fs.readFileSync(path.join(root, 'assets/icons/whatsapp.svg'), 'utf8');
  const brandPath = new JSDOM(brand).window.document.querySelector('path').getAttribute('d');
  assert.ok(decodeURIComponent(whatsapp.getAttribute('style')).includes(brandPath));
  const rendered = dom.window.document.querySelectorAll('svg').length;
  dom.window.HabibiUx.createIcons();
  assert.equal(
    dom.window.document.querySelectorAll('svg').length,
    rendered,
    'refreshing must leave hydrated icons intact',
  );
  dom.window.close();
});

test('Notes and Markdown load separately and retain parser licensing', () => {
  const launcher = fs.readFileSync(path.join(root, 'assets/app.bundle.js'), 'utf8');
  const notes = fs.readFileSync(path.join(root, 'assets/notes.bundle.js'), 'utf8');
  assert.ok(!launcher.includes('Your thoughts, connected.'));
  assert.ok(notes.includes('Your thoughts, connected.'));
  assert.match(notes, /Marked — MIT License/);
  assert.ok(
    notes.length < 650000,
    'the rich document engine and Markdown parser stay within the lazy Notes budget',
  );
});

test('action icons use named UX catalog components with no locally drawn SVGs', () => {
  const source = fs.readFileSync(path.join(root, 'src/client/ux/glyph.jsx'), 'utf8');
  assert.match(source, /IconMoreH/);
  assert.match(source, /from '@clidey\/ux'/);
  assert.doesNotMatch(source, /<path|<circle|<rect|from ['"]lucide-react/);
});
