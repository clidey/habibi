import assert from 'node:assert/strict';

export async function checkNotesDragUi(page) {
  const create = async title => {
    await page.locator('#notes-new').click();
    await page.waitForFunction(() => document.querySelector('#note-title')?.value === '');
    await page.locator('#note-title').fill(title);
    await page.locator('.tiptap').fill(`Content of ${title}`);
  };
  const row = title => page.locator('.notes-list-item').filter({ has: page.getByText(title, { exact: true }) });
  const library = () => page.evaluate(async () => (await fetch('/api/notes')).json());
  await create('Drag Alpha'); await create('Drag Beta'); await create('Drag Gamma');
  await page.waitForTimeout(650);
  await row('Drag Alpha').dragTo(row('Drag Beta'));
  await page.locator('#notes-folder-name').waitFor();
  await page.locator('#notes-folder-name').fill('Grouped pages');
  await page.locator('#notes-folder-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  let saved = await library();
  const grouped = saved.folders.find(folder => folder.name === 'Grouped pages');
  assert.ok(grouped, 'dropping onto another page must create a folder');
  assert.equal(saved.notes.filter(note => note.folderId === grouped.id).length, 2);
  const alpha = saved.notes.find(note => note.title === 'Drag Alpha');
  const beta = saved.notes.find(note => note.title === 'Drag Beta');
  await row('Drag Beta').dragTo(row('Drag Alpha'), { targetPosition: { x: 20, y: 2 } });
  await page.waitForTimeout(250);
  saved = await library();
  assert.ok(saved.noteOrder.indexOf(beta.id) < saved.noteOrder.indexOf(alpha.id), 'dropping at the edge must reorder without creating a folder');
  await page.locator('.notes-collection-picker > summary').click();
  await page.locator('[data-folder="all"]').click();
  const gamma = row('Drag Gamma');
  const bounds = await gamma.boundingBox();
  await page.mouse.move(bounds.x + 20, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + 35, bounds.y + bounds.height / 2 + 8, { steps: 5 });
  await page.locator('.notes-workspace.notes-dragging').waitFor();
  await page.locator('.notes-collection-picker > summary').hover();
  await page.locator('.notes-collection-picker > summary').hover();
  await page.waitForFunction(() => document.querySelector('.notes-collection-picker')?.open);
  const target = page.locator(`[data-folder="${grouped.id}"]`);
  await target.hover();
  await target.hover();
  await page.waitForFunction(id => document.querySelector(`[data-folder="${id}"]`)?.dataset.noteDrop === 'inside', grouped.id);
  await page.mouse.up();
  await page.waitForTimeout(250);
  saved = await library();
  assert.equal(saved.notes.filter(note => note.folderId === grouped.id).length, 3);
  assert.equal(saved.notes.find(note => note.title === 'Drag Gamma').body, 'Content of Drag Gamma');
  await row('Drag Alpha').click({ modifiers: ['Meta'] });
  await row('Drag Beta').click({ modifiers: ['Meta'] });
  assert.equal(await page.locator('.notes-drag-selected').count(), 2);
  await row('Drag Alpha').dragTo(page.locator('#notes-drop-group'));
  await page.locator('#notes-folder-name').waitFor();
  await page.locator('#notes-dialog-close').click();
  saved = await library();
  assert.equal(saved.folders.length, 1, 'cancelling a group must leave the library unchanged');
  assert.equal(saved.notes.filter(note => note.folderId === grouped.id).length, 3);
  await row('Drag Alpha').dragTo(page.locator('#notes-drop-group'));
  await page.locator('#notes-folder-name').waitFor();
  await page.locator('#notes-folder-name').fill('Selected pair');
  await page.locator('#notes-folder-save').click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  saved = await library();
  const pair = saved.folders.find(folder => folder.name === 'Selected pair');
  assert.equal(pair.parentId, grouped.id);
  assert.equal(saved.notes.filter(note => note.folderId === pair.id).length, 2);
  assert.equal(saved.notes.find(note => note.title === 'Drag Gamma').folderId, grouped.id);
  console.log('Notes drag check passed: grouping, reordering, folder moves, multiple selection and cancellation.');
}
