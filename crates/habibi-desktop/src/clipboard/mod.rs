//! Opt-in clipboard history (ported from `ClipboardHistory.swift`).
//!
//! Clipboard content stays in a bounded private local store under
//! `state_root/.habibi/clipboard/`, outside the service/model pipeline. The
//! history file keeps the Swift app's JSON shape (including its
//! `createdAt` encoding: seconds since 2001-01-01) so existing history loads.

use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

use crate::prefs::Preferences;
use crate::{fsutil, images};

#[cfg(target_os = "macos")]
mod macos;
#[cfg(not(target_os = "macos"))]
mod portable;

#[cfg(target_os = "macos")]
pub use macos::SystemBoard;
#[cfg(not(target_os = "macos"))]
pub use portable::SystemBoard;

const ENABLED_KEY: &str = "clipboardHistoryEnabled";
const MAX_ENTRIES: usize = 100;
const MAX_IMAGES: usize = 8;
const MAX_PINNED: usize = 20;
const MAX_TEXT_BYTES: usize = 64 * 1024;
const RETENTION_SECONDS: f64 = 7.0 * 86_400.0;
/// Seconds between the Unix epoch and Foundation's reference date.
const REFERENCE_DATE_OFFSET: f64 = 978_307_200.0;
const IMAGE_EXTENSIONS: &[&str] =
    &["png", "jpg", "jpeg", "tif", "tiff", "heic", "heif", "gif", "webp", "bmp", "avif"];

/// What the system clipboard currently holds, in the Swift app's priority:
/// files, then an image, then text.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct Clip {
    /// Advertised representation types (used to honour "concealed" markers).
    pub types: Vec<String>,
    pub files: Vec<PathBuf>,
    /// Encoded image bytes, already converted to PNG.
    pub image: Option<Vec<u8>>,
    pub text: Option<String>,
}

/// The per-OS clipboard.
pub trait Board: Send {
    /// A value that changes whenever the clipboard does, if the OS has one.
    /// `None` means the history compares content instead.
    fn change_marker(&mut self) -> Option<i64>;
    fn read(&mut self) -> Clip;
    /// (bundle identifier or executable path, display name) of the app that
    /// owns the frontmost window.
    fn frontmost_app(&mut self) -> (String, Option<String>);
    fn write_text(&mut self, text: &str) -> bool;
    fn write_png(&mut self, png: &[u8]) -> bool;
    fn write_file(&mut self, path: &Path) -> bool;
    /// The clipboard image as PNG, trying every fallback the OS offers. Used
    /// for an explicit paste, so it may be slower than [`Board::read`].
    fn image_png(&mut self) -> Option<Vec<u8>>;
    fn has_image(&mut self) -> bool;
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardEntry {
    pub id: String,
    pub kind: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub path: Option<String>,
    pub name: String,
    pub source: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub preview_path: Option<String>,
    /// Seconds since 2001-01-01T00:00:00Z (Swift `JSONEncoder` default).
    pub created_at: f64,
    pub pinned: bool,
}

/// Concealed/transient markers and password managers are never recorded.
pub fn permits(types: &[String], bundle: &str) -> bool {
    const BLOCKED_TYPES: &[&str] = &[
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        // Windows equivalents password managers set on their copies.
        "ExcludeClipboardContentFromMonitorProcessing",
        "Clipboard Viewer Ignore",
        // KDE/Linux password-manager hint.
        "x-kde-passwordManagerHint",
    ];
    const BLOCKED_APPS: &[&str] = &["password", "keychain", "1password", "bitwarden", "lastpass", "keepass", "dashlane"];
    let bundle = bundle.to_lowercase();
    !types.iter().any(|kind| BLOCKED_TYPES.contains(&kind.as_str()))
        && !BLOCKED_APPS.iter().any(|name| bundle.contains(name))
}

fn now_reference() -> f64 {
    SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_secs_f64()).unwrap_or(0.0) - REFERENCE_DATE_OFFSET
}

/// `ISO8601DateFormatter` default output, e.g. `2026-11-12T18:49:04Z`.
pub fn iso8601(reference_seconds: f64) -> String {
    let unix = (reference_seconds + REFERENCE_DATE_OFFSET).floor() as i64;
    let days = unix.div_euclid(86_400);
    let seconds = unix.rem_euclid(86_400);
    // Howard Hinnant's civil-from-days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!(
        "{year:04}-{month:02}-{day:02}T{:02}:{:02}:{:02}Z",
        seconds / 3600,
        (seconds / 60) % 60,
        seconds % 60
    )
}

fn content_hash(clip: &Clip) -> i64 {
    use std::hash::{Hash, Hasher};
    let mut hasher = std::collections::hash_map::DefaultHasher::new();
    clip.files.hash(&mut hasher);
    clip.image.hash(&mut hasher);
    clip.text.hash(&mut hasher);
    hasher.finish() as i64
}

pub struct ClipboardHistory {
    board: Box<dyn Board>,
    prefs: Arc<Preferences>,
    directory: PathBuf,
    file: PathBuf,
    entries: Vec<ClipboardEntry>,
    last_change: Option<i64>,
    sleeping: bool,
}

impl ClipboardHistory {
    pub fn new(state_root: &Path, board: Box<dyn Board>, prefs: Arc<Preferences>) -> Self {
        let directory = state_root.join(".habibi").join("clipboard");
        let file = directory.join("history.json");
        let entries = std::fs::read(&file)
            .ok()
            .filter(|data| data.len() < 16_000_000)
            .and_then(|data| serde_json::from_slice::<Vec<ClipboardEntry>>(&data).ok())
            .map(|saved| saved.into_iter().take(MAX_ENTRIES).collect())
            .unwrap_or_default();
        let mut history = Self { board, prefs, directory, file, entries, last_change: None, sleeping: false };
        history.last_change = history.marker();
        history.prune();
        history.save();
        history
    }

    pub fn enabled(&self) -> bool {
        self.prefs.get_bool(ENABLED_KEY).unwrap_or(false)
    }

    /// Pause capture while the screen sleeps or the session is inactive.
    pub fn set_sleeping(&mut self, sleeping: bool) {
        self.sleeping = sleeping;
        if !sleeping {
            self.last_change = self.marker();
        }
    }

    pub fn sleeping(&self) -> bool {
        self.sleeping
    }

    fn marker(&mut self) -> Option<i64> {
        match self.board.change_marker() {
            Some(marker) => Some(marker),
            None => Some(content_hash(&self.board.read())),
        }
    }

    /// Returns true when the history changed.
    pub fn set_enabled(&mut self, value: bool) -> bool {
        self.prefs.set(ENABLED_KEY, Value::Bool(value));
        self.last_change = None;
        if value {
            self.capture();
        }
        true
    }

    /// Record the clipboard if it changed. Returns true when an entry was added.
    pub fn capture(&mut self) -> bool {
        if !self.enabled() || self.sleeping {
            return false;
        }
        let (clip, marker) = match self.board.change_marker() {
            Some(marker) => {
                if Some(marker) == self.last_change {
                    return false;
                }
                (self.board.read(), marker)
            }
            None => {
                let clip = self.board.read();
                (clip.clone(), content_hash(&clip))
            }
        };
        if Some(marker) == self.last_change {
            return false;
        }
        self.last_change = Some(marker);
        let (bundle, name) = self.board.frontmost_app();
        if !permits(&clip.types, &bundle) {
            return false;
        }
        let source = name.unwrap_or_else(|| "Clipboard".into());
        if !clip.files.is_empty() {
            let mut added = false;
            for path in clip.files.iter().take(5) {
                if std::fs::File::open(path).is_err() {
                    continue;
                }
                let extension = path.extension().and_then(|e| e.to_str()).unwrap_or("").to_lowercase();
                let mut preview = None;
                if IMAGE_EXTENSIONS.contains(&extension.as_str())
                    && std::fs::metadata(path).map(|m| m.len() as usize <= images::MAXIMUM_BYTES).unwrap_or(false)
                    && let Ok(data) = std::fs::read(path)
                {
                    preview = self.save_preview(&data);
                }
                let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("File").to_string();
                self.append("file", None, Some(path.to_string_lossy().into_owned()), name, source.clone(), preview);
                added = true;
            }
            return added;
        }
        if let Some(png) = clip.image {
            let path = self.directory.join("images").join(format!("{}.png", new_id()));
            if self.prepare().is_ok() && fsutil::write_private(&path, &png).is_ok() {
                let preview = self.save_preview(&png);
                self.append(
                    "image",
                    None,
                    Some(path.to_string_lossy().into_owned()),
                    "Copied image.png".into(),
                    source,
                    preview,
                );
                return true;
            }
            return false;
        }
        if let Some(text) = clip.text
            && !text.trim().is_empty()
            && text.len() <= MAX_TEXT_BYTES
        {
            let name: String = text.chars().take(120).collect();
            self.append("text", Some(text), None, name, source, None);
            return true;
        }
        false
    }

    fn images_dir(&self) -> PathBuf {
        self.directory.join("images")
    }

    fn save_preview(&self, data: &[u8]) -> Option<String> {
        let preview = images::thumbnail(data)?;
        let path = self.images_dir().join(format!("{}.preview.png", new_id()));
        self.prepare().ok()?;
        fsutil::write_private(&path, &preview).ok()?;
        Some(path.to_string_lossy().into_owned())
    }

    fn append(
        &mut self,
        kind: &str,
        text: Option<String>,
        path: Option<String>,
        name: String,
        source: String,
        preview_path: Option<String>,
    ) {
        let old = self.entries.iter().find(|entry| entry.kind == kind && entry.text == text && entry.path == path).cloned();
        if let Some(old) = &old {
            self.remove_preview(old);
            self.entries.retain(|entry| entry.id != old.id);
        }
        self.entries.insert(
            0,
            ClipboardEntry {
                id: old.as_ref().map(|old| old.id.clone()).unwrap_or_else(new_id),
                kind: kind.into(),
                text,
                path,
                name,
                source,
                preview_path,
                created_at: now_reference(),
                pinned: old.map(|old| old.pinned).unwrap_or(false),
            },
        );
        self.prune();
        self.save();
    }

    fn prune(&mut self) {
        let now = now_reference();
        let mut keep: Vec<ClipboardEntry> =
            self.entries.iter().filter(|e| e.pinned || now - e.created_at < RETENTION_SECONDS).cloned().collect();
        keep.sort_by(|a, b| {
            b.pinned.cmp(&a.pinned).then(b.created_at.partial_cmp(&a.created_at).unwrap_or(std::cmp::Ordering::Equal))
        });
        let mut images = 0;
        let next: Vec<ClipboardEntry> = keep
            .into_iter()
            .filter(|entry| {
                if entry.kind == "image" {
                    images += 1;
                    images <= MAX_IMAGES
                } else {
                    true
                }
            })
            .take(MAX_ENTRIES)
            .collect();
        let removed: Vec<ClipboardEntry> =
            self.entries.iter().filter(|entry| !next.iter().any(|kept| kept.id == entry.id)).cloned().collect();
        for entry in &removed {
            self.remove_image(entry);
        }
        self.entries = next;
    }

    fn prepare(&self) -> std::io::Result<()> {
        fsutil::ensure_private_dir(&self.directory)?;
        fsutil::ensure_private_dir(&self.images_dir())
    }

    fn save(&self) {
        if self.prepare().is_err() {
            return;
        }
        if let Ok(data) = serde_json::to_vec(&self.entries) {
            let _ = fsutil::write_private(&self.file, &data);
        }
    }

    /// Only files Habibi itself created under `clipboard/images/` are deleted.
    fn owned(&self, path: &str) -> bool {
        let images = self.images_dir();
        let candidate = Path::new(path);
        candidate.starts_with(&images) && candidate != images && !path.contains("..")
    }

    fn remove_preview(&self, entry: &ClipboardEntry) {
        if let Some(path) = &entry.preview_path
            && self.owned(path)
        {
            let _ = std::fs::remove_file(path);
        }
    }

    fn remove_image(&self, entry: &ClipboardEntry) {
        self.remove_preview(entry);
        if entry.kind == "image"
            && let Some(path) = &entry.path
            && self.owned(path)
        {
            let _ = std::fs::remove_file(path);
        }
    }

    pub fn snapshot(&mut self) -> Value {
        self.capture();
        let items: Vec<Value> = self
            .entries
            .iter()
            .map(|item| {
                json!({
                    "id": item.id,
                    "kind": item.kind,
                    "text": item.text.clone().unwrap_or_default(),
                    "path": item.path.clone().unwrap_or_default(),
                    "name": item.name,
                    "source": item.source,
                    "previewPath": item.preview_path.clone().unwrap_or_default(),
                    "createdAt": iso8601(item.created_at),
                    "pinned": item.pinned,
                })
            })
            .collect();
        json!({ "ok": true, "enabled": self.enabled(), "items": items })
    }

    pub fn copy(&mut self, id: &str) -> bool {
        let Some(item) = self.entries.iter().find(|entry| entry.id == id).cloned() else { return false };
        let ok = if let Some(path) = item.path.as_deref().filter(|path| std::fs::File::open(path).is_ok()) {
            if item.kind == "image"
                && let Ok(data) = std::fs::read(path)
            {
                self.board.write_png(&data)
            } else {
                self.board.write_file(Path::new(path))
            }
        } else if let Some(text) = &item.text {
            self.board.write_text(text)
        } else {
            return false;
        };
        self.last_change = self.marker();
        ok
    }

    pub fn remove(&mut self, id: Option<&str>) {
        let removed: Vec<ClipboardEntry> =
            self.entries.iter().filter(|entry| id.is_none() || Some(entry.id.as_str()) == id).cloned().collect();
        for entry in &removed {
            self.remove_image(entry);
        }
        self.entries.retain(|entry| !(id.is_none() || Some(entry.id.as_str()) == id));
        self.save();
    }

    pub fn pin(&mut self, id: &str, value: bool) -> bool {
        let pinned = self.entries.iter().filter(|entry| entry.pinned).count();
        let Some(index) = self.entries.iter().position(|entry| entry.id == id) else { return false };
        if value && !self.entries[index].pinned && pinned >= MAX_PINNED {
            return false;
        }
        self.entries[index].pinned = value;
        self.prune();
        self.save();
        true
    }

    /// Direct access to the clipboard for explicit copy/paste requests.
    pub fn board(&mut self) -> &mut dyn Board {
        self.board.as_mut()
    }

    /// Record that Habibi itself just wrote the clipboard.
    pub fn note_own_write(&mut self) {
        self.last_change = self.marker();
    }
}

fn new_id() -> String {
    uuid::Uuid::new_v4().to_string().to_uppercase()
}

/// Read an image file path out of a list of clipboard files (Swift's
/// `furl` fallback for explicit paste).
pub fn image_from_files(files: &[PathBuf]) -> Option<Vec<u8>> {
    const EXTENSIONS: &[&str] = &["png", "jpg", "jpeg", "gif", "webp", "tiff", "heic"];
    let file = files.iter().find(|file| {
        file.extension().and_then(|e| e.to_str()).map(|e| EXTENSIONS.contains(&e.to_lowercase().as_str())).unwrap_or(false)
    })?;
    if std::fs::metadata(file).ok()?.len() as usize > images::MAXIMUM_INPUT_BYTES {
        return None;
    }
    images::png(&std::fs::read(file).ok()?)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::Mutex;

    #[derive(Default)]
    struct FakeState {
        count: i64,
        clip: Clip,
        app: String,
        written: Vec<String>,
    }

    #[derive(Clone, Default)]
    struct FakeBoard(Arc<Mutex<FakeState>>);

    impl FakeBoard {
        fn put(&self, clip: Clip) {
            let mut state = self.0.lock().unwrap();
            state.count += 1;
            state.clip = clip;
        }
    }

    impl Board for FakeBoard {
        fn change_marker(&mut self) -> Option<i64> {
            Some(self.0.lock().unwrap().count)
        }
        fn read(&mut self) -> Clip {
            self.0.lock().unwrap().clip.clone()
        }
        fn frontmost_app(&mut self) -> (String, Option<String>) {
            let app = self.0.lock().unwrap().app.clone();
            (app.clone(), Some(app))
        }
        fn write_text(&mut self, text: &str) -> bool {
            let mut state = self.0.lock().unwrap();
            state.count += 1;
            state.written.push(text.into());
            true
        }
        fn write_png(&mut self, _: &[u8]) -> bool {
            true
        }
        fn write_file(&mut self, _: &Path) -> bool {
            true
        }
        fn image_png(&mut self) -> Option<Vec<u8>> {
            None
        }
        fn has_image(&mut self) -> bool {
            false
        }
    }

    fn text(value: &str) -> Clip {
        Clip { text: Some(value.into()), ..Clip::default() }
    }

    fn history() -> (tempfile::TempDir, FakeBoard, ClipboardHistory) {
        let dir = tempfile::tempdir().unwrap();
        let prefs = Arc::new(Preferences::open(dir.path().join("prefs.json")));
        let board = FakeBoard::default();
        board.0.lock().unwrap().app = "com.apple.TextEdit".into();
        let history = ClipboardHistory::new(dir.path(), Box::new(board.clone()), prefs);
        (dir, board, history)
    }

    #[test]
    fn records_only_when_enabled_and_changed() {
        let (_dir, board, mut history) = history();
        board.put(text("hello"));
        assert!(!history.capture());
        history.set_enabled(true);
        assert_eq!(history.snapshot()["items"].as_array().unwrap().len(), 1);
        assert!(!history.capture(), "unchanged clipboard is not recorded twice");
        board.put(text("hello"));
        history.capture();
        assert_eq!(history.entries.len(), 1, "same text de-duplicates");
        board.put(text("   "));
        assert!(!history.capture(), "blank text is ignored");
    }

    #[test]
    fn skips_concealed_types_and_password_managers() {
        assert!(!permits(&["org.nspasteboard.ConcealedType".into()], "com.apple.Safari"));
        assert!(!permits(&[], "com.1password.1password"));
        assert!(!permits(&["ExcludeClipboardContentFromMonitorProcessing".into()], ""));
        assert!(permits(&["public.utf8-plain-text".into()], "com.apple.TextEdit"));
        let (_dir, board, mut history) = history();
        history.set_enabled(true);
        board.0.lock().unwrap().app = "com.bitwarden.desktop".into();
        board.put(text("secret"));
        assert!(!history.capture());
    }

    #[test]
    fn pins_are_capped_and_history_persists_in_swift_shape() {
        let (dir, board, mut history) = history();
        history.set_enabled(true);
        for index in 0..22 {
            board.put(text(&format!("item {index}")));
            history.capture();
        }
        let ids: Vec<String> = history.entries.iter().map(|e| e.id.clone()).collect();
        for id in ids.iter().take(20) {
            assert!(history.pin(id, true));
        }
        assert!(!history.pin(&ids[20], true));
        let saved: Value = serde_json::from_slice(&std::fs::read(dir.path().join(".habibi/clipboard/history.json")).unwrap()).unwrap();
        let first = &saved[0];
        assert!(first["createdAt"].is_f64());
        assert!(first.get("path").is_none(), "nil optionals are omitted like Swift's encoder");
        history.remove(None);
        assert!(history.entries.is_empty());
    }

    #[test]
    fn copy_writes_back_without_rerecording() {
        let (_dir, board, mut history) = history();
        history.set_enabled(true);
        board.put(text("again"));
        history.capture();
        let id = history.entries[0].id.clone();
        assert!(history.copy(&id));
        assert!(!history.capture());
        assert_eq!(board.0.lock().unwrap().written, vec!["again".to_string()]);
    }

    #[test]
    fn formats_dates_like_iso8601_date_formatter() {
        // 2001-01-01T00:00:00Z is the reference date itself.
        assert_eq!(iso8601(0.0), "2001-01-01T00:00:00Z");
        assert_eq!(iso8601(1_794_509_344.0 - REFERENCE_DATE_OFFSET), "2026-11-12T18:49:04Z");
    }
}
