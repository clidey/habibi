import AppKit

struct ClipboardEntry: Codable {
  let id: String
  let kind: String
  let text: String?
  let path: String?
  let name: String
  let source: String
  let previewPath: String?
  let createdAt: Date
  var pinned: Bool
}

/** Clipboard content stays in a bounded private local store, outside the service/model pipeline. */
final class ClipboardHistory {
  private let board: NSPasteboard
  private let defaults: UserDefaults
  private let monitorsChanges: Bool
  private let directory: URL
  private let file: URL
  private var entries: [ClipboardEntry] = []
  private var timer: Timer?
  private var lastChange: Int
  private var sleeping = false
  private var observers: [NSObjectProtocol] = []
  var onChange: (() -> Void)?
  var enabled: Bool { defaults.bool(forKey: "clipboardHistoryEnabled") }
  init(root: URL, board: NSPasteboard = .general, defaults: UserDefaults = .standard, monitor: Bool = true) {
    self.board = board; self.defaults = defaults; self.monitorsChanges = monitor; self.lastChange = board.changeCount
    directory = root.appendingPathComponent(".habibi/clipboard", isDirectory: true)
    file = directory.appendingPathComponent("history.json")
    if let data = try? Data(contentsOf: file), data.count < 16_000_000, let saved = try? JSONDecoder().decode([ClipboardEntry].self, from: data) { entries = Array(saved.prefix(100)) }
    prune(); save()
    let center = NSWorkspace.shared.notificationCenter
    for name in [NSWorkspace.screensDidSleepNotification, NSWorkspace.sessionDidResignActiveNotification] {
      observers.append(center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in self?.sleeping = true; self?.configureTimer() })
    }
    for name in [NSWorkspace.screensDidWakeNotification, NSWorkspace.sessionDidBecomeActiveNotification] {
      observers.append(center.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in self?.sleeping = false; self?.lastChange = self?.board.changeCount ?? 0; self?.configureTimer() })
    }
    configureTimer()
  }
  deinit { timer?.invalidate(); for observer in observers { NSWorkspace.shared.notificationCenter.removeObserver(observer) } }
  func setEnabled(_ value: Bool) { defaults.set(value, forKey: "clipboardHistoryEnabled"); lastChange = board.changeCount - 1; if value { capture() }; configureTimer(); onChange?() }
  private func configureTimer() {
    timer?.invalidate(); timer = nil
    guard enabled, !sleeping, monitorsChanges else { return }
    let next = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.capture() }
    next.tolerance = 0.4; RunLoop.main.add(next, forMode: .common); timer = next
  }
  static func permits(types: [String], bundle: String) -> Bool {
    let blocked = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
    return !types.contains(where: { blocked.contains($0) }) && !["password", "keychain", "1password", "bitwarden", "lastpass", "keepass", "dashlane"].contains(where: { bundle.lowercased().contains($0) })
  }
  private func capture() {
    guard enabled, !sleeping else { return }
    guard board.changeCount != lastChange else { return }
    lastChange = board.changeCount
    let app = NSWorkspace.shared.frontmostApplication
    guard Self.permits(types: (board.types ?? []).map { $0.rawValue }, bundle: app?.bundleIdentifier ?? "") else { return }
    let source = app?.localizedName ?? "Clipboard"
    if let files = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !files.isEmpty {
      for url in files.prefix(5) where FileManager.default.isReadableFile(atPath: url.path) {
        let extensions = ["png", "jpg", "jpeg", "tif", "tiff", "heic", "heif", "gif", "webp", "bmp", "avif"]
        var preview: String?
        if extensions.contains(url.pathExtension.lowercased()), let size = try? url.resourceValues(forKeys: [.fileSizeKey]).fileSize, size <= ClipboardImages.maximumBytes, let data = try? Data(contentsOf: url) { preview = savePreview(data) }
        append(kind: "file", text: nil, path: url.path, name: url.lastPathComponent, source: source, previewPath: preview)
      }
    } else if let data = ClipboardImages.png(from: board) {
      let url = directory.appendingPathComponent("images/\(UUID().uuidString).png")
      do { try prepare(); try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700]); try data.write(to: url, options: .atomic); try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path); append(kind: "image", text: nil, path: url.path, name: "Copied image.png", source: source, previewPath: savePreview(data)) } catch { }
    } else if let value = board.string(forType: .string), !value.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, value.utf8.count <= 64 * 1024 {
      append(kind: "text", text: value, path: nil, name: String(value.prefix(120)), source: source)
    }
  }
  private func savePreview(_ data: Data) -> String? {
    guard let preview = ClipboardImages.thumbnail(data) else { return nil }
    let url = directory.appendingPathComponent("images/\(UUID().uuidString).preview.png")
    do { try prepare(); try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700]); try preview.write(to: url, options: .atomic); try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path); return url.path } catch { return nil }
  }
  private func append(kind: String, text: String?, path: String?, name: String, source: String, previewPath: String? = nil) {
    let old = entries.first { $0.kind == kind && $0.text == text && $0.path == path }
    if let old { removePreview(old) }
    entries.removeAll { $0.id == old?.id }
    entries.insert(ClipboardEntry(id: old?.id ?? UUID().uuidString, kind: kind, text: text, path: path, name: name, source: source, previewPath: previewPath, createdAt: Date(), pinned: old?.pinned ?? false), at: 0)
    prune(); save(); onChange?()
  }
  private func prune() {
    let keep = entries.filter { $0.pinned || Date().timeIntervalSince($0.createdAt) < 7 * 86400 }.sorted { a, b in a.pinned != b.pinned ? a.pinned : a.createdAt > b.createdAt }
    var images = 0
    let next = Array(keep.filter { entry in if entry.kind == "image" { images += 1; return images <= 8 }; return true }.prefix(100))
    for entry in entries where !next.contains(where: { $0.id == entry.id }) { removeImage(entry) }
    entries = next
  }
  private func prepare() throws { try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700]); try FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: directory.path) }
  private func save() { do { try prepare(); let data = try JSONEncoder().encode(entries); try data.write(to: file, options: .atomic); try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path) } catch { } }
  private func removePreview(_ entry: ClipboardEntry) { if let path = entry.previewPath, path.hasPrefix(directory.appendingPathComponent("images").path + "/") { try? FileManager.default.removeItem(atPath: path) } }
  private func removeImage(_ entry: ClipboardEntry) { removePreview(entry); if entry.kind == "image", let path = entry.path, path.hasPrefix(directory.appendingPathComponent("images").path + "/") { try? FileManager.default.removeItem(atPath: path) } }
  func snapshot() -> [String: Any] {
    capture()
    let values: [[String: Any]] = entries.map { item in ["id": item.id, "kind": item.kind, "text": item.text ?? "", "path": item.path ?? "", "name": item.name, "source": item.source, "previewPath": item.previewPath ?? "", "createdAt": ISO8601DateFormatter().string(from: item.createdAt), "pinned": item.pinned] }
    return ["ok": true, "enabled": enabled, "items": values]
  }
  func copy(_ id: String) -> Bool {
    guard let item = entries.first(where: { $0.id == id }) else { return false }
    if let path = item.path, FileManager.default.isReadableFile(atPath: path) {
      if item.kind == "image", let data = try? Data(contentsOf: URL(fileURLWithPath: path)) { board.clearContents(); let ok = board.setData(data, forType: .png); lastChange = board.changeCount; return ok }
      board.clearContents(); let ok = board.writeObjects([URL(fileURLWithPath: path) as NSURL]); lastChange = board.changeCount; return ok
    }
    guard let text = item.text else { return false }
    board.clearContents(); let ok = board.setString(text, forType: .string); lastChange = board.changeCount; return ok
  }
  func remove(_ id: String?) { for entry in entries where id == nil || entry.id == id { removeImage(entry) }; entries.removeAll { id == nil || $0.id == id }; save(); onChange?() }
  func pin(_ id: String, value: Bool) -> Bool {
    guard let index = entries.firstIndex(where: { $0.id == id }), !value || entries[index].pinned || entries.filter({ $0.pinned }).count < 20 else { return false }
    entries[index].pinned = value; prune(); save(); onChange?(); return true
  }
}
